/// <reference types="node" />
import fs from 'fs';
import path from 'path';
import { GOLDEN_CASES } from '../golden/cases';
import thresholds from '../thresholds.json';
import { rate, scoreAll, type OfflineReport } from './score';

const RESULTS_DIR = path.join(process.cwd(), 'evals', 'results');

const LABELS: Record<keyof OfflineReport['metrics'], string> = {
  classificationAccuracy: 'Product type classification',
  tokenRecall: 'Ingredient extraction (recall)',
  noiseRejection: 'Non-ingredient text rejected',
  allergenSurvival: 'Declared allergens reach the model',
  edcDetection: 'Endocrine disruptors detected',
};

const toMarkdown = (report: OfflineReport): string => {
  const floors = thresholds.offline as Record<string, number>;
  const rows = (Object.keys(LABELS) as (keyof typeof LABELS)[]).map(key => {
    const t = report.metrics[key];
    const r = rate(t);
    return `| ${LABELS[key]} | ${t.passed}/${t.total} | ${(r * 100).toFixed(0)}% | ${(floors[key] * 100).toFixed(0)}% | ${r >= floors[key] ? '✅' : '❌'} |`;
  });
  const failures = report.cases
    .flatMap(c => [
      c.productType.expected !== c.productType.actual &&
        `- \`${c.id}\`: classified ${c.productType.actual}, expected ${c.productType.expected}`,
      ...c.missingTokens.map(t => `- \`${c.id}\`: ingredient "${t}" not extracted`),
      ...c.leakedText.map(t => `- \`${c.id}\`: non-ingredient text "${t}" sent as an ingredient`),
      ...c.lostAllergens.map(a => `- \`${c.id}\`: declared allergen ${a} never reaches the model`),
      ...c.missedEdcs.map(e => `- \`${c.id}\`: EDC ${e} not detected`),
    ])
    .filter(Boolean);
  return [
    `# Offline eval results`,
    ``,
    `Golden cases: ${report.cases.length}. Generated by \`npm run evals:offline\`; do not edit by hand.`,
    ``,
    `| Metric | Passed | Score | Floor | |`,
    `|---|---|---|---|---|`,
    ...rows,
    ``,
    `## Known failures`,
    ``,
    ...(failures.length ? failures : ['None.']),
    ``,
  ].join('\n');
};

describe('offline eval tier (pre-LLM pipeline vs golden set)', () => {
  const report = scoreAll(GOLDEN_CASES);

  beforeAll(() => {
    fs.mkdirSync(RESULTS_DIR, { recursive: true });
    fs.writeFileSync(
      path.join(RESULTS_DIR, 'offline.json'),
      JSON.stringify(report, null, 2) + '\n',
    );
    fs.writeFileSync(path.join(RESULTS_DIR, 'offline.md'), toMarkdown(report));
  });

  it.each(Object.entries(thresholds.offline))(
    '%s stays at or above its floor (%s)',
    (metric, floor) => {
      const score = rate(report.metrics[metric as keyof OfflineReport['metrics']]);
      expect(score).toBeGreaterThanOrEqual(floor);
    },
  );
});
